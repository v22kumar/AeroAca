#!/usr/bin/env node
/**
 * Runs every lab in labs/manifest.json and writes lib/labs/generated.ts with the exact
 * source text, command and output. Run it after changing a lab; CI (tests/labs.test.ts)
 * runs the labs again and fails if the committed outputs no longer match.
 *
 *   node scripts/sync-labs.mjs            # regenerate
 *   node scripts/sync-labs.mjs --check    # exit 1 if anything would change
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const manifest = JSON.parse(readFileSync(join(root, "labs/manifest.json"), "utf8"));
const check = process.argv.includes("--check");

export function runLab(lab) {
  const cwd = join(root, lab.dir);
  const output = execSync(lab.command, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, LC_ALL: "C", PYTHONHASHSEED: "0" } });
  return output.replace(/\r\n/g, "\n").trimEnd();
}

const entries = manifest.labs.map((lab) => {
  const code = readFileSync(join(root, lab.dir, lab.file), "utf8").replace(/\r\n/g, "\n").trimEnd();
  let expectedOutput;
  try {
    expectedOutput = runLab(lab);
  } catch (e) {
    // A lab whose command is expected to exit non-zero (a known-failing test) still has useful stdout.
    if (lab.id.includes("known-failure") && e.stdout) expectedOutput = String(e.stdout).replace(/\r\n/g, "\n").trimEnd();
    else throw e;
  }
  return { ...lab, code, expectedOutput };
});

const header = `/* GENERATED by scripts/sync-labs.mjs from labs/manifest.json. Do not edit by hand. */
export type LabLanguage = "c" | "cpp" | "python" | "bash";
export type Lab = { id: string; dir: string; language: LabLanguage; file: string; command: string; code: string; expectedOutput: string };

export const labs: Record<string, Lab> = `;
const body = JSON.stringify(Object.fromEntries(entries.map((e) => [e.id, e])), null, 2);
const out = `${header}${body};

export function getLab(id: string): Lab | undefined {
  return labs[id];
}
`;
const target = join(root, "lib/labs/generated.ts");
if (check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("lib/labs/generated.ts is out of date; run node scripts/sync-labs.mjs");
    process.exit(1);
  }
  console.log(`labs in sync (${entries.length})`);
} else {
  writeFileSync(target, out);
  console.log(`wrote lib/labs/generated.ts (${entries.length} labs)`);
}
